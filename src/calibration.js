// 項目ごとの「結果への出やすさ」をそろえる係数。
//
// 重視度は exp(a) * max(m, 1-m)^2 で決まるが、この値の水準は項目ごとに違う。
// 理想値 m が端に寄りやすい項目は max(m, 1-m)^2 が最大4倍になるため、
// 重視していなくても上位3つに紛れ込む。逆に中央へ寄る項目は重視していても埋もれる。
// 実測では、上位3つに出る割合が項目間で 1.63倍 ひらいていた（本来はどれも 21.4%）。
//
// そこで重視度に項目ごとの係数を掛けて水準をそろえる。
//
// **21.4% ぴったりに強制してはいけない。** 係数を強くかけるほど出やすさはそろうが、
// その項目を本当に重視している人まで弾いてしまう。
// 強さ 0.45 が、出やすさと当てやすさの両方が同時に良くなる点だった。
//
//   強さ   出やすさの幅   当てやすさの幅   当てやすさ最小
//   0.00      1.63倍         1.46倍          53.6%
//   0.45      1.33倍         1.42倍          53.7%   ← これを使う
//   0.80      1.36倍         1.54倍          50.7%
//
// 残る 1.33倍 / 1.42倍 は係数では詰められない。当てやすさは項目どうしの
// 相関で決まっており、そこを動かすには顔を足すしかない。
//
// 値の求め方:
//   node tools/calibrate.mjs 45 400            満額の係数が出る
//   その係数を 0.45 乗したものをここに貼る
//
// **calibrate.mjs の「後」の数字は当てにしないこと。** 係数を求めたのと同じ
// サンプルで効果を報告しているので過学習している（満額で 1.06倍 と出るが、
// 別の乱数で測ると 1.51倍 だった）。強さを選ぶときは別の乱数で測り直す。
//
// プールを大きく変えたら測り直す。
