// 項目ごとの「結果への出やすさ」をそろえる係数。
//
// 重視度は exp(a) * max(m, 1-m)^2 で決まるが、この値の水準は項目ごとに違う。
// 理想値 m が端に寄りやすい項目は max(m, 1-m)^2 が最大4倍になるため、
// 重視していなくても上位3つに紛れ込む。逆に中央へ寄る項目は重視していても埋もれる。
// 実測では、上位3つに出る割合が項目間で 1.90倍 ひらいていた（本来はどれも 20%）。
//
// そこで重視度に項目ごとの係数を掛けて水準をそろえる。
//
// **20% ぴったりに強制してはいけない。** 係数を強くかけるほど出やすさはそろうが、
// その項目を本当に重視している人まで弾いてしまう。輪郭の縦横比は 20% に
// 強制すると当てやすさが 63.0% → 47.1% まで落ちた。
// 強さ 0.45 が、出やすさと当てやすさの両方が同時に良くなる点だった。
//
//   強さ   出やすさの幅   当てやすさの幅   当てやすさ最小
//   0.00      1.90倍         1.50倍          55.6%
//   0.45      1.52倍         1.43倍          58.3%   ← これを使う
//   1.00      1.00倍         1.74倍          47.1%
//
// 残る 1.52倍 / 1.43倍 は係数では詰められない。当てやすさは項目どうしの
// 相関で決まっており（相関 -0.70）、そこを動かすには顔を足すしかない。
//
// 値の求め方:  node tools/calibrate.mjs 45 400
// プールを大きく変えたら測り直す。
